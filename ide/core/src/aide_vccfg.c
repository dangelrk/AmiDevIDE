#include "aide/aide_vccfg.h"
#include "aide/aide_str.h"

#include <stdlib.h>

char *aide_vccfg_generate(const AideToolchainConfig *toolchain, const AideProject *project)
{
    return aide_vccfg_generate_dialect(toolchain, project, aide_makegen_host_dialect());
}

char *aide_vccfg_generate_dialect(const AideToolchainConfig *toolchain, const AideProject *project,
                                   AideMakeDialect dialect)
{
    AideStr s;
    char *vbccm68k = aide_toolchain_vbccm68k_path(toolchain);
    char *vasm = aide_toolchain_vasm_path(toolchain);
    char *includeDir = aide_toolchain_include_dir(toolchain);
    const char *sdOpt = project->compiler.smallData ? " -sd" : "";

    aide_str_init(&s);
    /* No leading "# comment" line here (unlike aide_makegen.c's actual
     * Makefiles, which `make` really does treat "#" as a comment in) --
     * vc.cfg has no comment syntax at all: per vc's own docs, "every
     * line of the file will be used as one argument" verbatim, so a
     * "#..." line was being handed to vc as if it were a positional
     * file/pattern argument, which AmigaDOS then reported as "No match
     * for # Generated by AmigaIDE..." (confirmed via a real build log,
     * once the +/-I/-o quoting and "delete" fixes got far enough to
     * actually reach this line). */

    aide_str_append(&s, "-cc=");
    aide_str_append(&s, vbccm68k);
    aide_str_append(&s, " -quiet");
    aide_str_append(&s, sdOpt);
    aide_str_append(&s, " %s -o= %s %s -O=%ld -I");
    aide_str_append(&s, includeDir);
    aide_str_append_char(&s, '\n');

    aide_str_append(&s, "-ccv=");
    aide_str_append(&s, vbccm68k);
    aide_str_append(&s, sdOpt);
    aide_str_append(&s, " %s -o= %s %s -O=%ld -I");
    aide_str_append(&s, includeDir);
    aide_str_append_char(&s, '\n');

    aide_str_append(&s, "-as=");
    aide_str_append(&s, vasm);
    aide_str_append(&s, " -quiet -Fhunk -nowarn=62 %s -o %s\n");

    aide_str_append(&s, "-asv=");
    aide_str_append(&s, vasm);
    aide_str_append(&s, " -Fhunk -nowarn=62 %s -o %s\n");

    /* vc.cfg's -rm=/-rmv= directives tell vc how to clean up its own
     * intermediate temp files -- and that command runs on whatever host
     * vc ITSELF executes on, which differs by which side generated this
     * config: the Qt IDE cross-compiles from macOS (real "rm" available)
     * while the native MUI app runs vc directly on AmigaOS (no "rm" at
     * all, confirmed via a real build log: "rm: Unbekannter Befehl",
     * caught only once actual compilation got past the earlier +/-I/-o
     * quoting issues far enough to reach the cleanup step -- AmigaDOS's
     * own equivalent is "delete"). Decided by the caller-supplied
     * `dialect`, not inferred from __M68K__ in here -- a call site that
     * only ever runs on one specific host (the native Amiga app) should
     * say so directly rather than rely on a compiler macro to guess it
     * right, see aide_vccfg_generate_dialect()'s own doc comment. */
    if (dialect == AIDE_MAKE_DIALECT_AMIGADOS) {
        aide_str_append(&s, "-rm=delete %s\n");
        aide_str_append(&s, "-rmv=delete %s\n");
    } else {
        aide_str_append(&s, "-rm=rm -f %s\n");
        aide_str_append(&s, "-rmv=rm %s\n");
    }
    aide_str_append(&s, "-ul=-l%s\n");
    aide_str_append(&s, "-cf=-F%s\n");
    aide_str_append(&s, "-ml=1000\n");
    aide_str_append(&s, "-hunkdebug\n");
    aide_str_append(&s, "-amiga-softfloat\n");

    free(vbccm68k);
    free(vasm);
    free(includeDir);

    return aide_str_take(&s);
}
