#!/bin/sh
#
# Regenerates core/src/aide_basic_keywords.c from the ACE repo's CubicIDE
# dictionaries, which are the maintained source of truth for the language's
# vocabulary (the ACE repo's AGENTS.md requires them to be updated whenever
# a keyword or function is added or removed). Keeping this a generator
# rather than a hand-written table means the IDE follows ACE automatically.
#
# Usage: core/tools/gen_basic_keywords.sh [path-to-ace-tree]
#
# The default is the patched ACE tree the bootstrap assembles under var/
# (cmake --build build --target acd-ace-src).
#
set -eu

ace=${1:-$(cd "$(dirname "$0")/../../.." && pwd)/var/src/acebasic}
dict=$ace/IDE/CubicIDE-ACE/add-ons/ace/syntax/dictionaries
out=$(cd "$(dirname "$0")/.." && pwd)/src/aide_basic_keywords.c

for f in commands functions; do
    [ -f "$dict/$f" ] || { echo "not found: $dict/$f" >&2; exit 1; }
done

emit_list() {
    # One quoted entry per line, sorted, blanks dropped. Multi-word entries
    # ("AREA STEP", "END SUB") are kept whole: the highlighter matches them
    # as phrases, and dropping them would lose the second word's context.
    LC_ALL=C sort -u "$1" | sed '/^[[:space:]]*$/d' \
        | sed 's/[[:space:]]*$//' \
        | awk '{ printf "    \"%s\",\n", $0 }'
}

{
    echo '/* Generated by core/tools/gen_basic_keywords.sh -- DO NOT EDIT.'
    echo ' *'
    echo ' * Source: the ACE repo'"'"'s IDE/CubicIDE-ACE/add-ons/ace/syntax/'
    echo ' * dictionaries/{commands,functions}, which ACE keeps in step with the'
    echo ' * language. Re-run the generator after updating the ACE checkout. */'
    echo
    echo '#include "aide/aide_keywords.h"'
    echo
    echo 'static const char *const kBasicCommands[] = {'
    emit_list "$dict/commands"
    echo '};'
    echo
    echo 'static const char *const kBasicFunctions[] = {'
    emit_list "$dict/functions"
    echo '};'
    echo
    cat <<'EOF'
const char *const *aide_keywords_basic_commands(size_t *outCount)
{
    *outCount = sizeof(kBasicCommands) / sizeof(kBasicCommands[0]);
    return kBasicCommands;
}

const char *const *aide_keywords_basic_functions(size_t *outCount)
{
    *outCount = sizeof(kBasicFunctions) / sizeof(kBasicFunctions[0]);
    return kBasicFunctions;
}
EOF
} > "$out"

echo "wrote $out"
